using System.Diagnostics.CodeAnalysis;
using System.Globalization;

namespace Sentinel.Core.Devices;

/// <summary>
/// A Plug and Play device instance ID, e.g. <c>USBSTOR\DISK&amp;VEN_SMI&amp;PROD_USB_DISK&amp;REV_1100\6&amp;172B058&amp;1</c>:
/// enumerator, device ID, and instance segment. Comparison is case-insensitive, as in Windows.
/// </summary>
public sealed class PnpInstanceId : IEquatable<PnpInstanceId>
{
    private PnpInstanceId(string value, string enumerator, string deviceId, string instanceSegment)
    {
        Value = value;
        Enumerator = enumerator;
        DeviceId = deviceId;
        InstanceSegment = instanceSegment;
    }

    public string Value { get; }

    /// <summary>Bus enumerator, e.g. <c>USB</c>, <c>USBSTOR</c>, <c>SCSI</c>.</summary>
    public string Enumerator { get; }

    /// <summary>Device ID part, e.g. <c>VID_090C&amp;PID_1000</c> or <c>DISK&amp;VEN_SMI&amp;PROD_USB_DISK&amp;REV_1100</c>.</summary>
    public string DeviceId { get; }

    /// <summary>Instance segment: a device serial number, or an ID generated by Windows.</summary>
    public string InstanceSegment { get; }

    /// <summary>
    /// True when Windows generated the instance segment because the device reported no unique serial
    /// (<c>UniqueID=FALSE</c>). Such IDs depend on the port the device is plugged into. Windows marks them
    /// with '&amp;' as the second character, e.g. <c>6&amp;172B058&amp;1</c>.
    /// </summary>
    public bool IsSystemGenerated => InstanceSegment.Length > 1 && InstanceSegment[1] == '&';

    public static bool TryParse(string? value, [NotNullWhen(true)] out PnpInstanceId? id)
    {
        id = null;
        var sanitized = DeviceStrings.Sanitize(value);
        if (sanitized is null)
        {
            return false;
        }

        var parts = sanitized.Split('\\');
        if (parts.Length != 3 || parts.Any(string.IsNullOrWhiteSpace))
        {
            return false;
        }

        id = new PnpInstanceId(sanitized, parts[0], parts[1], parts[2]);
        return true;
    }

    /// <summary>
    /// Serial number embedded in the instance segment, or null when Windows generated the segment.
    /// A USBSTOR LUN suffix (<c>&amp;0</c>) is removed.
    /// </summary>
    public string? GetDeviceSerial()
    {
        if (IsSystemGenerated)
        {
            return null;
        }

        var ampersand = InstanceSegment.LastIndexOf('&');
        var serial = ampersand > 0 && Enumerator.Equals("USBSTOR", StringComparison.OrdinalIgnoreCase)
            ? InstanceSegment[..ampersand]
            : InstanceSegment;

        return serial.Length == 0 ? null : serial;
    }

    /// <summary>Parses <c>VID_xxxx&amp;PID_yyyy</c> from a <c>USB\</c> device ID.</summary>
    public bool TryGetUsbVidPid(out ushort vendorId, out ushort productId)
    {
        vendorId = 0;
        productId = 0;
        if (!Enumerator.Equals("USB", StringComparison.OrdinalIgnoreCase))
        {
            return false;
        }

        bool hasVid = false, hasPid = false;
        foreach (var token in DeviceId.Split('&'))
        {
            if (token.StartsWith("VID_", StringComparison.OrdinalIgnoreCase))
            {
                hasVid = ushort.TryParse(token.AsSpan(4), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out vendorId);
            }
            else if (token.StartsWith("PID_", StringComparison.OrdinalIgnoreCase))
            {
                hasPid = ushort.TryParse(token.AsSpan(4), NumberStyles.HexNumber, CultureInfo.InvariantCulture, out productId);
            }
        }

        return hasVid && hasPid;
    }

    /// <summary>Parses <c>VEN_/PROD_/REV_</c> from a disk device ID (<c>USBSTOR\DISK&amp;VEN_…</c>, <c>SCSI\DISK&amp;VEN_…</c>).</summary>
    public StorageDescriptor? GetStorageDescriptor()
    {
        string? vendor = null, product = null, revision = null;
        foreach (var token in DeviceId.Split('&'))
        {
            if (token.StartsWith("VEN_", StringComparison.OrdinalIgnoreCase))
            {
                vendor = token[4..];
            }
            else if (token.StartsWith("PROD_", StringComparison.OrdinalIgnoreCase))
            {
                product = token[5..];
            }
            else if (token.StartsWith("REV_", StringComparison.OrdinalIgnoreCase))
            {
                revision = token[4..];
            }
        }

        return vendor is null && product is null ? null : new StorageDescriptor(vendor, product, revision);
    }

    public bool Equals(PnpInstanceId? other) =>
        other is not null && string.Equals(Value, other.Value, StringComparison.OrdinalIgnoreCase);

    public override bool Equals(object? obj) => Equals(obj as PnpInstanceId);

    public override int GetHashCode() => StringComparer.OrdinalIgnoreCase.GetHashCode(Value);

    public override string ToString() => Value;
}

/// <summary>Vendor, product, and revision strings as reported by the storage device (not necessarily the retail brand).</summary>
public sealed record StorageDescriptor(string? Vendor, string? Product, string? Revision);
